
"""
IMISI HealthGrid PoC - care authorisation workflow API.

All data is synthetic. This is a demonstration workflow,
not a production healthcare authorisation system.
"""

import json
import uuid
from datetime import datetime, timezone

from flask import Blueprint, jsonify, request

from eligibility import get_db

bp = Blueprint("authorisations", __name__)

VALID_STATUSES = {
    "draft",
    "submitted",
    "under_review",
    "more_info_needed",
    "approved",
    "declined",
    "cancelled",
    "closed",
}

VALID_URGENCIES = {"routine", "urgent"}

ALLOWED_TRANSITIONS = {
    "draft": {"submitted", "cancelled"},
    "submitted": {"under_review", "cancelled"},
    "under_review": {
        "more_info_needed",
        "approved",
        "declined",
        "cancelled",
    },
    "more_info_needed": {"submitted", "cancelled"},
    "approved": {"closed"},
    "declined": {"closed"},
    "cancelled": set(),
    "closed": set(),
}


def now_ts():
    """Return a consistent ISO-style UTC timestamp."""
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%S")


def parse_json_list(value):
    """Decode a JSON list stored in the database."""
    if not value:
        return []

    try:
        result = json.loads(value)
        return result if isinstance(result, list) else []
    except (TypeError, ValueError):
        return []


def request_dict(row):
    """Convert a database request row into a JSON-friendly dictionary."""
    result = dict(row)
    result["missing_fields"] = parse_json_list(
        result.get("missing_fields")
    )
    result["simulated"] = True
    return result


def record_event(
    db,
    request_id,
    actor,
    from_state,
    to_state,
    reason=None,
):
    """Append an audit event. event_id is generated by SQLite."""
    db.execute(
        """
        INSERT INTO workflow_events (
            request_id,
            actor,
            from_state,
            to_state,
            reason,
            created_at
        )
        VALUES (?, ?, ?, ?, ?, ?)
        """,
        (
            request_id,
            actor,
            from_state,
            to_state,
            reason,
            now_ts(),
        ),
    )


def get_request_row(db, request_id):
    return db.execute(
        """
        SELECT *
        FROM authorisation_requests
        WHERE request_id = ?
        """,
        (request_id,),
    ).fetchone()


@bp.route("/api/authorisations", methods=["POST"])
def create_authorisation():
    """Create a new care authorisation request."""
    data = request.get_json(silent=True)

    if not isinstance(data, dict):
        return jsonify({
            "error": "Request body must be a JSON object."
        }), 400

    required_fields = [
        "member_id",
        "provider_id",
        "service_category",
        "service_description",
    ]

    missing = [
        field for field in required_fields
        if not isinstance(data.get(field), str)
        or not data[field].strip()
    ]

    if missing:
        return jsonify({
            "error": "Required fields are missing or invalid.",
            "missing_fields": missing,
        }), 400

    member_id = data["member_id"].strip()
    provider_id = data["provider_id"].strip()
    service_category = data["service_category"].strip()
    service_description = data["service_description"].strip()

    urgency = data.get("urgency", "routine")
    if urgency not in VALID_URGENCIES:
        return jsonify({
            "error": "urgency must be routine or urgent."
        }), 400

    estimated_cost = data.get("estimated_cost_ngn")

    if estimated_cost is not None:
        # Reject booleans, which Python otherwise treats as integers.
        if (
            isinstance(estimated_cost, bool)
            or not isinstance(estimated_cost, (int, float))
            or estimated_cost < 0
        ):
            return jsonify({
                "error": "estimated_cost_ngn must be a non-negative number."
            }), 400

        if isinstance(estimated_cost, float) and not estimated_cost.is_integer():
            return jsonify({
                "error": "estimated_cost_ngn must be a whole number."
            }), 400

        estimated_cost = int(estimated_cost)

    requested_date = data.get("requested_date")
    if requested_date is not None:
        if not isinstance(requested_date, str) or not requested_date.strip():
            return jsonify({
                "error": "requested_date must be a non-empty ISO date."
            }), 400

        try:
            datetime.strptime(requested_date, "%Y-%m-%d")
        except ValueError:
            return jsonify({
                "error": "requested_date must use YYYY-MM-DD format."
            }), 400

    reason = data.get("reason")
    if reason is not None and not isinstance(reason, str):
        return jsonify({
            "error": "reason must be a string."
        }), 400

    db = get_db()

    try:
        member = db.execute(
            "SELECT member_id FROM members WHERE member_id = ?",
            (member_id,),
        ).fetchone()

        if member is None:
            return jsonify({"error": "Member not found."}), 404

        provider = db.execute(
            "SELECT provider_id FROM providers WHERE provider_id = ?",
            (provider_id,),
        ).fetchone()

        if provider is None:
            return jsonify({"error": "Provider not found."}), 404

        request_id = "AUTH-" + uuid.uuid4().hex[:8].upper()
        timestamp = now_ts()
        initial_status = "submitted"

        db.execute(
            """
            INSERT INTO authorisation_requests (
                request_id,
                member_id,
                provider_id,
                service_category,
                service_description,
                requested_date,
                urgency,
                estimated_cost_ngn,
                reason,
                status,
                missing_fields,
                created_at,
                updated_at
            )
            VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
            """,
            (
                request_id,
                member_id,
                provider_id,
                service_category,
                service_description,
                requested_date,
                urgency,
                estimated_cost,
                reason.strip() if reason else None,
                initial_status,
                json.dumps([]),
                timestamp,
                timestamp,
            ),
        )

        record_event(
            db,
            request_id,
            "provider_user",
            None,
            initial_status,
            "Authorisation request created",
        )

        db.commit()

        return jsonify({
            "request_id": request_id,
            "status": initial_status,
            "created_at": timestamp,
            "simulated": True,
        }), 201

    except Exception:
        db.rollback()
        bp.logger.exception("Failed to create authorisation request")
        return jsonify({
            "error": "Unable to create authorisation request."
        }), 500


@bp.route("/api/authorisations", methods=["GET"])
def list_authorisations():
    """List authorisation requests, optionally filtered by status."""
    status = request.args.get("status")

    if status and status not in VALID_STATUSES:
        return jsonify({
            "error": "Invalid status.",
            "valid_statuses": sorted(VALID_STATUSES),
        }), 400

    try:
        limit = int(request.args.get("limit", 100))
    except (TypeError, ValueError):
        return jsonify({"error": "limit must be an integer."}), 400

    if limit < 1 or limit > 100:
        return jsonify({
            "error": "limit must be between 1 and 100."
        }), 400

    db = get_db()

    if status:
        rows = db.execute(
            """
            SELECT *
            FROM authorisation_requests
            WHERE status = ?
            ORDER BY created_at DESC
            LIMIT ?
            """,
            (status, limit),
        ).fetchall()
    else:
        rows = db.execute(
            """
            SELECT *
            FROM authorisation_requests
            ORDER BY created_at DESC
            LIMIT ?
            """,
            (limit,),
        ).fetchall()

    return jsonify({
        "count": len(rows),
        "requests": [request_dict(row) for row in rows],
        "simulated": True,
    }), 200


@bp.route("/api/authorisations/<request_id>", methods=["GET"])
def get_authorisation(request_id):
    """Retrieve a request and its audit history."""
    db = get_db()
    row = get_request_row(db, request_id)

    if row is None:
        return jsonify({"error": "Authorisation request not found."}), 404

    event_rows = db.execute(
        """
        SELECT event_id, request_id, actor, from_state,
               to_state, reason, created_at
        FROM workflow_events
        WHERE request_id = ?
        ORDER BY event_id ASC
        """,
        (request_id,),
    ).fetchall()

    return jsonify({
        "request": request_dict(row),
        "events": [dict(event) for event in event_rows],
        "simulated": True,
    }), 200


@bp.route(
    "/api/authorisations/<request_id>/status",
    methods=["PATCH"],
)
def update_authorisation_status(request_id):
    """Validate a status transition and append its audit event."""
    data = request.get_json(silent=True)

    if not isinstance(data, dict):
        return jsonify({
            "error": "Request body must be a JSON object."
        }), 400

    new_status = data.get("status")
    actor = data.get("actor")
    reason = data.get("reason")

    if new_status not in VALID_STATUSES:
        return jsonify({
            "error": "Invalid status.",
            "valid_statuses": sorted(VALID_STATUSES),
        }), 400

    if not isinstance(actor, str) or not actor.strip():
        return jsonify({
            "error": "A non-empty actor is required."
        }), 400

    actor = actor.strip()

    if reason is not None and not isinstance(reason, str):
        return jsonify({"error": "reason must be a string."}), 400

    if new_status in {"approved", "declined"} and (
        not isinstance(reason, str) or not reason.strip()
    ):
        return jsonify({
            "error": "A reason is required for approval or decline."
        }), 400

    db = get_db()

    try:
        row = get_request_row(db, request_id)

        if row is None:
            return jsonify({
                "error": "Authorisation request not found."
            }), 404

        previous_status = row["status"]

        if new_status not in ALLOWED_TRANSITIONS.get(previous_status, set()):
            return jsonify({
                "error": "Status transition is not allowed.",
                "current_status": previous_status,
                "requested_status": new_status,
                "allowed_next_statuses": sorted(
                    ALLOWED_TRANSITIONS.get(previous_status, set())
                ),
            }), 409

        timestamp = now_ts()

        db.execute(
            """
            UPDATE authorisation_requests
            SET status = ?, updated_at = ?
            WHERE request_id = ?
            """,
            (new_status, timestamp, request_id),
        )

        record_event(
            db,
            request_id,
            actor,
            previous_status,
            new_status,
            reason.strip() if reason else None,
        )

        db.commit()

        return jsonify({
            "request_id": request_id,
            "previous_status": previous_status,
            "status": new_status,
            "updated_at": timestamp,
            "simulated": True,
        }), 200

    except Exception:
        db.rollback()
        bp.logger.exception("Failed to update authorisation status")
        return jsonify({
            "error": "Unable to update authorisation status."
        }), 500
